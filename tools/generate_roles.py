"""Generate/check diagnostic role constants from the native eligibility policy."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render():
    text = (ROOT / 'native/common/soldier_roles.h').read_text(encoding='utf-8')
    block = re.search(r'human_tables\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
    roles = [(int(value, 16), name.strip()) for value, name in re.findall(r'(0x[0-9a-f]+),\s*//([^\n]+)', block)]
    if len(roles) != 10 or len(set(x[0] for x in roles)) != 10:
        raise ValueError('Review changes to the ten verified final human roles explicitly')
    horse = int(re.search(r'horse_table\s*=\s*(0x[0-9a-f]+)', text).group(1), 16)
    lines = ['"""Generated by tools/generate_roles.py; do not edit independently."""', 'HUMAN_TABLES = frozenset((']
    lines += [f'    {value:#x},  # {name}' for value, name in roles]
    lines += ['))', f'HORSE_TABLE = {horse:#x}', '', 'def human(engine, table):',
              '    return table >= engine and table - engine in HUMAN_TABLES', '',
              'def combat_actor(engine, table):',
              '    return human(engine, table) or (table >= engine and table - engine == HORSE_TABLE)', '']
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true', help='Check only (also the default)')
    args = parser.parse_args()
    target = ROOT / 'tools/diagnostics/source/actor_roles.py'
    expected = render()
    if args.write:
        target.write_text(expected, encoding='utf-8')
    if not target.is_file() or target.read_text(encoding='utf-8') != expected:
        raise SystemExit('Diagnostic role policy is stale: python tools/generate_roles.py --write')
    print('PASS: native and diagnostic role policies agree')

if __name__ == '__main__':
    main()
