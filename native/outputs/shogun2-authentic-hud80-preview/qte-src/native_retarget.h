namespace qte { namespace retarget {
using ReleaseActor=void(__thiscall*)(void*,void*);
using ReleaseAux=void(__thiscall*)(void*);
struct Ports {NativeWitnessCall prepare{};ReleaseActor release_actor{};ReleaseAux release_aux{};uint32_t engine{};};
template<class T>inline T& at(uint32_t object,unsigned offset){return *reinterpret_cast<T*>(object+offset);}
// Native-only transition on the engine callback thread. Both participants must
// still belong to this witness; never clear a competing encounter's backlink.
// Animation selection is rebuilt by original prepare, not by forcing clip or
// casualty flags. The native original selector is supplied its cached roles by
// the caller's replay scope, so this transition does not reroll combat roles.
inline uint32_t rebuild(uint32_t witness,const NativeVerdict& desired,const NativePlan* plans,const Ports& ports,uint32_t& stage,bool route152=false){
    stage=1;
    if(!plans||!ports.prepare||!ports.release_actor||!ports.release_aux||!witness)return 1;
    uint32_t prior_state[2]{},prior_clip[2]{},serial[2]{},unit[2]{},table[2]{};
    __try{
        if(at<uint8_t>(witness,0xc)!=1||at<uint8_t>(witness,0xd1)!=0||at<uint32_t>(witness,0x38)!=2||
           at<uint32_t>(witness,0x48)!=0||at<uint8_t>(witness,0xee)!=0)return 1;
        uint32_t a=at<uint32_t>(witness,0x30),b=at<uint32_t>(witness,0x34);
        if(a==b||!((a==plans[0].actor&&b==plans[1].actor)||(b==plans[0].actor&&a==plans[1].actor)))return 1;
        if(at<uint32_t>(witness,0x24)!=2)return 1;
        auto old_attacker=at<uint32_t>(witness,0x84),old_defender=at<uint32_t>(witness,0x88);
        if(route152){if(!((old_attacker==a&&old_defender==b)||(old_attacker==b&&old_defender==a)))return 1;}
        else if(old_attacker!=desired.attacker_address||old_defender!=desired.defender_address)return 1;
        if(!((desired.attacker_address==a&&desired.defender_address==b)||(desired.attacker_address==b&&desired.defender_address==a))||
           (desired.outcome!=0&&desired.outcome!=5))return 1;
        for(unsigned i=0;i<2;++i){auto actor=plans[i].actor;
            table[i]=at<uint32_t>(actor,0);
            if(!actor152::kind(ports.engine,table[i],plans[i].kind)||at<uint8_t>(actor,0xf0)!=1||
               at<uint32_t>(actor,0x688)!=witness||at<uint32_t>(actor,0x21c)||plans[i].state>0x100)return 1;
            if(plans[i].kind==Horse){
                Reader r{[](void*,uint32_t address,void* out,size_t size){SIZE_T n{};return ReadProcessMemory(GetCurrentProcess(),reinterpret_cast<void*>(address),out,size,&n)&&n==size;},nullptr};
                NativeActor horse,rider;if(!combat_identity(r,actor,ports.engine,horse)||!horse_rider(r,ports.engine,horse,rider))return 1;
            }
            serial[i]=at<uint32_t>(actor,0x1c8);unit[i]=at<uint32_t>(actor,0x214);
            prior_state[i]=at<uint32_t>(actor,0x1d0);prior_clip[i]=at<uint32_t>(actor,0x1d4);
        }
        // The prompt consumed wall/simulation time while the original prepare's
        // alignment deadline kept aging. Reprepare even the unchanged outcome,
        // so stock activation recomputes targets and its own deadline together.
        stage=2;
        ports.release_aux(reinterpret_cast<void*>(witness));
        for(unsigned i=0;i<2;++i)ports.release_actor(reinterpret_cast<void*>(witness),reinterpret_cast<void*>(plans[i].actor));
        // Use the captured native planning context to build the new variant,
        // rather than states changed by waiting/aiming during the prompt.
        for(unsigned i=0;i<2;++i){at<uint32_t>(plans[i].actor,0x1d0)=plans[i].state;at<uint32_t>(plans[i].actor,0x1d4)=plans[i].clip;}
        // On success retain the states/clips generated by original preparation;
        // restoring the pre-QTE plans would overwrite native alignment/animation.
        // 3e8b30 only invokes the original activation dispatcher when +0xd
        // is armed. Initial preparation consumed that byte. Without rearming,
        // rebuilding sets active=1 but never registers either actor's targets.
        at<uint8_t>(witness,0xc)=0;at<uint8_t>(witness,0xd)=1;at<uint8_t>(witness,0xd0)=0;
        at<uint8_t>(witness,0xd1)=0;at<uint8_t>(witness,0xd2)=0;at<uint8_t>(witness,0xd3)=0;
        at<uint8_t>(witness,0xec)=0;at<uint8_t>(witness,0xed)=0;
        stage=3;
        uint32_t answer=0;bool prepared_ok=false;
        __try{answer=ports.prepare(reinterpret_cast<void*>(witness));prepared_ok=(answer&0xff)==0;stage=4;}
        __finally{
            for(unsigned i=0;i<2&&!prepared_ok;++i){auto actor=plans[i].actor;
                if(at<uint32_t>(actor,0)==table[i]&&at<uint32_t>(actor,0x1c8)==serial[i]&&at<uint32_t>(actor,0x214)==unit[i]){
                    at<uint32_t>(actor,0x1d0)=prior_state[i];at<uint32_t>(actor,0x1d4)=prior_clip[i];
                }
            }
        }
        if(answer&0xff)return answer;
        if(at<uint8_t>(witness,0xc)!=1||at<uint32_t>(witness,0x80)!=desired.outcome||
           at<uint32_t>(witness,0x84)!=desired.attacker_address||at<uint32_t>(witness,0x88)!=desired.defender_address||
           at<uint32_t>(plans[0].actor,0x688)!=witness||at<uint32_t>(plans[1].actor,0x688)!=witness){stage=5;return 1;}
        stage=6;return answer;
    }__except(EXCEPTION_EXECUTE_HANDLER){stage=7;return 1;}
}
} }
